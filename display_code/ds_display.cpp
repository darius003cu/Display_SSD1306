void display_init() {
  uint8_t to_send[] = {SLAVE_W, 0, 0xAF};
  i2c_toggle(START);
  i2c_send(to_send, 3);
  i2c_toggle(STOP);
}

void charge_pump() {
  uint8_t to_send[] = {SLAVE_W, 0, 0x8D, 0x14};
  i2c_toggle(START);
  i2c_send(to_send, 4);
  i2c_toggle(STOP);
}


void clear_page() {
  uint8_t to_send[] = {SLAVE_W, 0x40};
  uint8_t zero[1] = {0x00};
  i2c_toggle(START);
  i2c_send(to_send, 2);
  for(uint8_t i=0; i<128; i++)
     {
     i2c_send(zero, 1);
     }
  i2c_toggle(STOP);
}

void page_setup(uint8_t nr) {
  uint8_t page = 0xB0 | nr;
  uint8_t to_send[] = {SLAVE_W, 0, page, 0x00, 0x10};
  i2c_toggle(START);
  i2c_send(to_send, 5);
  i2c_toggle(STOP);
}

void display_reset() {
  for(uint8_t i = 0; i < 8; i++) {
    page_setup(i);
    clear_page();
  }
}

